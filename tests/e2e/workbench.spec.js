import { test, expect } from '@playwright/test'

test('JWT inspection, validation and in-memory navigation', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/?tool=jwt')
  await page.getByRole('button', { name: 'Load example' }).click()
  await expect(page.getByText('Within time window', { exact: true })).toBeVisible()
  await expect(page.getByText('Signature unverified', { exact: true })).toBeVisible()
  const input = page.getByRole('textbox', { name: 'Encoded token' })
  const token = await input.inputValue()
  await page.getByRole('button', { name: 'JSON formatter', exact: true }).click()
  await page.getByRole('button', { name: 'JWT decoder', exact: true }).click()
  await expect(input).toHaveValue(token)
  await input.fill('bad.token')
  await expect(page.getByText(/must have three dot-separated/)).toBeVisible()
  await page.reload()
  await expect(input).toHaveValue('')
  expect(errors).toEqual([])
})

test('File diff reads files, compares, clears stale output, and exports patch', async ({ page }) => {
  await page.goto('/?tool=diff')
  const original = page.locator('.editor').filter({ has: page.getByText('Original', { exact: true }) })
  const modified = page.locator('.editor').filter({ has: page.getByText('Modified', { exact: true }) })
  await original.locator('input[type=file]').setInputFiles({ name: 'before.txt', mimeType: 'text/plain', buffer: Buffer.from('hello\nold\n') })
  await modified.locator('input[type=file]').setInputFiles({ name: 'after.txt', mimeType: 'text/plain', buffer: Buffer.from('hello\nnew\n') })
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await expect(page.getByText('+1 added', { exact: true })).toBeVisible()
  await expect(page.locator('.diff-line.removed code')).toHaveText('old')
  await expect(page.locator('.diff-line.added code')).toHaveText('new')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save patch' }).click()
  expect((await download).suggestedFilename()).toBe('comparison.patch')
  await page.getByRole('textbox', { name: 'Modified', exact: true }).fill('other')
  await expect(page.getByRole('button', { name: 'Save patch' })).toBeDisabled()
})

