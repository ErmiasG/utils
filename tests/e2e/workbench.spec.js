  await expect(page.locator('.diff-line.removed code')).toHaveText('old marker')
  await expect(page.locator('.diff-line.added code')).toHaveText('new marker')
  await expect(page.getByRole('button', { name: 'Save patch' })).toBeEnabled()
  const result = await page.locator('.diff-result').boundingBox()
  const lines = await page.locator('.diff-lines').boundingBox()
  expect(result.width).toBeGreaterThan(2000)
  expect(lines.height).toBeGreaterThan(650)
  expect(result.y + result.height).toBeGreaterThan(1570)
  expect(result.y + result.height).toBeLessThanOrEqual(1600)
