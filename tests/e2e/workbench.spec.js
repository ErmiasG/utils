test('Remaining tools, clipboard, downloads, browser history and visual review', async ({ page, context }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })
  await expect(page.getByRole('button', { name: 'Open navigation', exact: true })).not.toBeVisible()
  await page.screenshot({ path: '/tmp/utils-overview.png', fullPage: true })
  for (const [id, source] of [['html', '<main><h1>Hello</h1></main>'], ['xml', '<root><value>hello</value></root>']]) {
    await page.goto(`/?tool=${id}`)
    await page.getByRole('textbox', { name: 'Source', exact: true }).fill(source)
    await expect(page.locator('.document-preview code')).toContainText('hello', { ignoreCase: true })
    await page.getByRole('button', { name: 'Full width', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Source', exact: true })).not.toBeVisible()
    await page.getByRole('button', { name: 'Split view', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Source', exact: true })).toBeVisible()
  }
  await page.goto('/?tool=url')
  await page.getByRole('textbox', { name: 'Input', exact: true }).fill('a+b & café')
  await expect(page.getByRole('textbox', { name: 'Result' })).toHaveValue('a%2Bb%20%26%20caf%C3%A9')
  await page.getByRole('button', { name: 'Copy', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('a%2Bb%20%26%20caf%C3%A9')
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await page.getByRole('textbox', { name: 'Input', exact: true }).fill('%zz')
  await expect(page.getByText(/Invalid URL encoding/)).toBeVisible()
  await page.getByRole('button', { name: 'Hash generator', exact: true }).click()
  await page.locator('.tool-content:not([hidden]) input[type=file]').first().setInputFiles({ name: 'abc.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('abc') })
  await expect(page.locator('.hash-result pre')).toHaveText('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad')
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'URL encoder', exact: true })).toBeVisible()
  await page.goto('/?tool=jwt')
  await page.getByRole('button', { name: 'Load example' }).click()
  await page.screenshot({ path: '/tmp/utils-jwt.png', fullPage: true })
  await page.goto('/?tool=diff')
  await page.getByRole('button', { name: 'Load example' }).click()
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await expect(page.getByText('+3 added', { exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/utils-diff.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/utils-mobile-diff.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
